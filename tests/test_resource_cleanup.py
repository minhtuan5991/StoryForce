def test_interrupted_final_move_restores_the_original_reference(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    root=client.app.state.root
    target=files['folder']/'final_video.mp4'
    signature=files['final'].stat()
    with client.app.state.database.session() as db:
        render=db.query(Artifact).filter_by(kind='render_report').one()
        report_id=render.id
    journal=root/'projects'/('.storyforge-final-move-'+project['id']+'.json')
    write_json(journal,{'project_id':project['id'],'report_id':report_id,
        'source':str(files['final'].relative_to(root)),'target':str(target.relative_to(root)),
        'signature':[signature.st_size,signature.st_mtime_ns,signature.st_ino]})
    files['final'].rename(target)
    recover_final_moves(client.app.state.database,root)
    assert files['final'].read_bytes()==b'final video must remain byte identical'
    assert not target.exists() and not journal.exists()
    assert client.get('/api/projects/'+project['id']+'/download/final_video.mp4').status_code==200


