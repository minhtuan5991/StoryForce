def test_shared_files_and_untracked_system_files_are_preserved(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    other=client.post('/api/projects',json={'channel_id':project['channel_id'],'title':'Other story'}).json()
    with client.app.state.database.session() as db:
        db.add(Asset(project_id=other['id'],path=str(files['image'].relative_to(client.app.state.root)),kind='image'))
        db.commit()
    report=preview(client,project)
    assert not any(f['path']==str(files['image']) for f in report['files'])
    assert clean(client,project,report).status_code==200
    assert files['image'].is_file() and files['keep'].is_file()
    assert client.get('/api/projects/'+other['id']).status_code==200


def test_final_shared_with_another_project_is_not_moved(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    other=client.post('/api/projects',json={'channel_id':project['channel_id'],'title':'Shared final'}).json()
    with client.app.state.database.session() as db:
        db.add(Asset(project_id=other['id'],path=str(files['final'].relative_to(client.app.state.root)),kind='video'))
        db.commit()
    result=clean(client,project,preview(client,project))
    assert result.status_code==200 and Path(result.json()['final'])==files['final']
    assert files['final'].read_bytes()==b'final video must remain byte identical'


def test_locked_file_reports_partial_cleanup_and_retry(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    unlink=Path.unlink
    def locked(path,*args,**kwargs):
        if path==files['original']:raise PermissionError('File is in use')
        return unlink(path,*args,**kwargs)
    with patch.object(Path,'unlink',locked):
        response=clean(client,project,preview(client,project))
    assert response.status_code==200 and response.json()['status']=='partial'
    assert response.json()['failed_files'][0]['path']==str(files['original'])
    assert files['original'].is_file()
    response=clean(client,project,preview(client,project))
    assert response.status_code==200 and response.json()['cleaned'] and not files['original'].exists()
    reuse = client.get('/api/projects/'+project['id']).json()['premise_reuse']
    assert reuse['ready'], reuse


def test_owned_capcut_copy_is_cleaned_but_wrong_manifest_is_preserved(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    owned=tmp_path/'CapCut'/'Owned';foreign=tmp_path/'CapCut'/'Foreign'
    for directory,id in ((owned,project['id']),(foreign,'other-project')):
        directory.mkdir(parents=True);(directory/'media').mkdir();(directory/'media/clip.mp4').write_bytes(b'capcut media')
        manifest={'format':'storyforge-capcut','project_id':id,'draft_id':'draft-123','folder':str(directory)}
        (directory/'storyforge_export.json').write_text(json.dumps(manifest),encoding='utf-8')
        with client.app.state.database.session() as db:
            db.add(Artifact(project_id=project['id'],kind='capcut_export',content={**manifest,'project_id':project['id']}));db.commit()
    report=preview(client,project)
    assert any(f['scope']=='CapCut' for f in report['files'])
    assert clean(client,project,report).status_code==200
    assert not owned.exists() and (foreign/'media/clip.mp4').is_file()


