def finished(client, project, tmp_path, monkeypatch):
    root=client.app.state.root
    downloads=tmp_path/'Downloads';downloads.mkdir()
    monkeypatch.setattr('backend.media_automation.downloads_root',lambda:downloads)
    folder=project_path(root,project['id'])
    image=folder/'images/scene_001.png';image.write_bytes(b'generated image')
    audio=folder/'audio/tts_001.wav';audio.write_bytes(b'generated audio')
    final=folder/'render/v1/run/final_video.mp4';final.parent.mkdir(parents=True);final.write_bytes(b'final video must remain byte identical')
    cache=final.parent/'final_audio.wav';cache.write_bytes(b'intermediate audio')
    exported=root/'exports'/f"{project['id']}-project-v1.zip";exported.write_bytes(b'old export')
    external=downloads/project['title'];external.mkdir()
    original=external/'scene_001.png';original.write_bytes(b'generated image')
    keep=external/'personal-notes.txt';keep.write_bytes(b'not generated by the app')
    downloaded_final=external/'final_video.mp4';downloaded_final.write_bytes(final.read_bytes())
    with client.app.state.database.session() as db:
        p=db.get(Project,project['id']);p.locked=True;p.story_version=1;p.draft='The door remembered my name.';p.stage='READY';p.publish={'final_reviewed':True}
        idea=Premise(project_id=p.id,title=p.title);db.add(idea);db.flush();p.selected_premise_id=idea.id
        a=Asset(project_id=p.id,name='scene_001.png',path=str(image.relative_to(root)),kind='image',size=image.stat().st_size,sha256='image-hash',story_version=1,metadata_json={'download_path':str(original),'browser_download_id':1})
        b=Asset(project_id=p.id,name='tts_001.wav',path=str(audio.relative_to(root)),kind='audio',size=audio.stat().st_size,duration=10.0,sha256='audio-hash',story_version=1,metadata_json={'has_audio':True})
        db.add_all([a,b]);db.flush()
        c=Chunk(project_id=p.id,story_version=1,number=1,text=p.draft,word_count=5,real_duration=10.0,estimated_duration=10.0,asset_id=b.id,status='ATTACHED')
        s=Scene(project_id=p.id,story_version=1,number=1,end_word=5,duration=10.0,asset_id=a.id,status='ATTACHED')
        db.add_all([c,s]);db.commit();db.expire_all()
        p=db.get(Project,project['id'])
        rows=[[serialize(row) for row in db.query(model).filter_by(project_id=p.id)] for model in (Chunk,Scene,Asset)]
        content={'story_version':1,'status':'READY','file':str(final.relative_to(root)),'checks':{'video_present':True},'warnings':[],
                 'inputs_hash':render_inputs_hash(serialize(p),*rows,settings_for(db,db.get(Channel,p.channel_id)))}
        db.add(Artifact(project_id=p.id,kind='render_report',story_version=1,content=content));db.commit()
    return {'folder':folder,'image':image,'audio':audio,'final':final,'export':exported,'original':original,'keep':keep,'downloaded_final':downloaded_final}


def preview(client, project):
    response=client.get('/api/projects/'+project['id']+'/resources/cleanup-preview')
    assert response.status_code==200,response.text
    return response.json()


def clean(client, project, report):
    return client.post('/api/projects/'+project['id']+'/resources/cleanup',json={'confirmation':report['confirmation']})


def test_cleanup_retains_identical_final_story_reuse_and_download(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    before=client.get('/api/projects/'+project['id']).json()
    assert before['premise_reuse']['ready'], before['premise_reuse']
    expected=files['final'].read_bytes()
    report=preview(client,project)
    assert not report['blocked'] and report['was_current']
    assert any(f['path']==str(files['original']) for f in report['files'])
    result=clean(client,project,report)
    assert result.status_code==200,result.text
    final=Path(result.json()['final'])
    assert final==files['folder']/'final_video.mp4' and final.read_bytes()==expected
    assert not files['image'].exists() and not files['audio'].exists() and not files['export'].exists() and not files['original'].exists()
    assert files['keep'].is_file() and files['downloaded_final'].read_bytes()==expected
    assert [p for p in files['folder'].rglob('*') if p.is_file()]==[final]
    detail=client.get('/api/projects/'+project['id']).json()
    assert detail['draft']==before['draft'] and detail['locked'] and detail['premise_reuse']['ready']
    assert detail['assets']==[] and detail['chunks'][0]['asset_id'] is None and detail['chunks'][0]['real_duration'] is None
    assert detail['next']['action_kind']=='archived_resources'
    assert client.get('/api/projects/'+project['id']+'/download/final_video.mp4').content==expected
    downloaded=client.post('/api/projects/'+project['id']+'/download-final').json()
    assert downloaded['saved'] and Path(downloaded['path']).read_bytes()==expected
    assert [p for p in files['folder'].rglob('*') if p.is_file()]==[final]
    assert client.post('/api/projects/'+project['id']+'/pipeline').json()['action_kind']=='archived_resources'
    assert client.post('/api/jobs',json={'kind':'tts_context','project_id':project['id']}).status_code==422
    assert client.post('/api/projects/'+project['id']+'/resources/resume').json()['resumed']
    assert 'resource_cleanup' not in client.get('/api/projects/'+project['id']).json()['settings']


def test_preview_change_or_active_job_cannot_delete(client,project,tmp_path,monkeypatch):
    files=finished(client,project,tmp_path,monkeypatch)
    report=preview(client,project);files['image'].write_bytes(b'changed')
    assert clean(client,project,report).status_code==409 and files['final'].is_file() and files['image'].is_file()
    with client.app.state.database.session() as db:db.add(Job(project_id=project['id'],kind='render',status='running'));db.commit()
    report=preview(client,project)
    assert report['blocked'] and clean(client,project,report).status_code==409
    assert files['audio'].is_file()


